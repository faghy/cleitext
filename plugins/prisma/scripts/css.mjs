// Builds src/public/prisma.css: the shared styles (src/styles/prisma.css), then each
// block's own (src/blocks/<name>/style.css). Run it after changing any of them:
// `pnpm css` (a test checks the result is up to date).
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));

export function buildCss() {
  const parts = [readFileSync(`${root}src/styles/prisma.css`, 'utf8').trimEnd()];
  for (const name of readdirSync(`${root}src/blocks`).sort()) {
    const file = `${root}src/blocks/${name}/style.css`;
    if (existsSync(file))
      parts.push(`/* ---- ${name} ---- */\n${readFileSync(file, 'utf8').trimEnd()}`);
  }
  return `/* Generated by scripts/css.mjs from src/styles and each block's style.css: do not edit. */\n${parts.join('\n')}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(`${root}src/public/prisma.css`, buildCss());
}
