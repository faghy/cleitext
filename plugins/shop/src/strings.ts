export type Translate = (text: string, values?: Record<string, string | number>) => string;

export function translator(locale: string): Translate {
  const catalog = locale.startsWith('it') ? IT : {};
  return (text, values) => {
    const translated = catalog[text] ?? text;
    return values
      ? translated.replace(/\{(\w+)\}/g, (m, k: string) => (k in values ? String(values[k]) : m))
      : translated;
  };
}
