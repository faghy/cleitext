export function stringsFor(locale: string): Strings {
  return locale.toLowerCase().startsWith('it') ? IT : EN;
}

/** `{name}` placeholders filled with values. */
export function fill(text: string, values: Record<string, string | number>): string {
  return text.replace(/\{(\w+)\}/g, (all, key: string) =>
    values[key] === undefined ? all : String(values[key]),
  );
}
